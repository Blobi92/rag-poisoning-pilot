"""Analyze R2 + Phase D runs -> verification/RESULTS.md and verification/results.html.

Implements the pre-registered analysis: pooled counts over poison sets, Wilson 95% CIs,
exact McNemar on paired per-question outcomes.
Usage: python verification/analyze.py
"""
import html
import json
import math
from pathlib import Path

from scipy.stats import binomtest

ROOT = Path(__file__).resolve().parent.parent
V = ROOT / "verification"
D = V / "runs" / "phaseD"

ARMS = [
    ("1_baseline", "1 Baseline (open ingestion)"),
    ("2_allowlist", "2 Allowlist"),
    ("3_compromised", "3 Compromised source"),
    ("4_compromised+screen", "4 + Screening"),
    ("5_screen+hybrid", "5 + Hybrid (RRF k=60)"),
    ("6_screen+corroborate", "6 + Corroboration"),
    ("7p_content-verify-honest", "7′ Content verify (honest)"),
    ("8nv_compromised-canonical-noverify", "8nv Poisoned canonical, no verify"),
    ("8_compromised-canonical+verify", "8 Poisoned canonical + verify"),
    ("9_snapshot-manifest", "9 Snapshot manifest"),
]
PAIRS = [("1_baseline", "2_allowlist"), ("3_compromised", "4_compromised+screen"),
         ("4_compromised+screen", "5_screen+hybrid"), ("4_compromised+screen", "6_screen+corroborate"),
         ("3_compromised", "7p_content-verify-honest"),
         ("8_compromised-canonical+verify", "8nv_compromised-canonical-noverify"),
         ("3_compromised", "9_snapshot-manifest")]


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    den = 1 + z * z / n
    c = (p + z * z / (2 * n)) / den
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return (max(0.0, c - h), min(1.0, c + h))


def mcnemar(a, b):
    """exact McNemar on paired booleans."""
    b01 = sum(1 for x, y in zip(a, b) if x and not y)
    b10 = sum(1 for x, y in zip(a, b) if y and not x)
    n = b01 + b10
    p = 1.0 if n == 0 else binomtest(b01, n, 0.5).pvalue
    return b01, b10, p


def load_sets():
    sets = {}
    for f in sorted(D.glob("results_S*.json")):
        sets[f.stem.replace("results_", "")] = json.load(open(f))
    return sets


def r2_table():
    ship = json.load(open(ROOT / "results.json"))
    r2p = V / "runs" / "r2" / "results.json"
    if not r2p.exists():
        return [], {}
    r2 = json.load(open(r2p))
    meta = json.load(open(V / "runs" / "r2" / "meta.json"))
    rows = []
    for k, x in ship.items():
        y = r2.get(k)
        if not y:
            rows.append((k, x, None, None))
            continue
        same = sum(a["answer"] == b["answer"] for a, b in
                   zip(x["target_rows"] + x["clean_rows"], y["target_rows"] + y["clean_rows"]))
        rows.append((k, x, y, same))
    return rows, meta


def main():
    sets = load_sets()
    names = list(sets)
    agg = {}
    for key, label in ARMS:
        per = {s: sets[s].get(key) for s in names}
        have = {s: v for s, v in per.items() if v}
        if not have:
            continue
        n = 20 * len(have)
        g = sum(v["summary"]["norm_gen_asr"] for v in have.values())
        r = sum(v["summary"]["retrieval_asr"] for v in have.values())
        graw = sum(v["summary"]["raw_gen_asr"] for v in have.values())
        cor = sum(v["summary"]["target_correct"] for v in have.values())
        cl = sum(v["summary"]["norm_clean"] for v in have.values())
        fr = [v["info"]["trusted_false_rejections"] for v in have.values()]
        agg[key] = dict(label=label, n=n, sets=len(have), gen=g, ret=r, graw=graw, cor=cor,
                        clean=cl, nclean=10 * len(have), fr=fr,
                        per={s: v["summary"]["norm_gen_asr"] for s, v in have.items()},
                        ci=wilson(g, n), rci=wilson(r, n),
                        vec={s: [row["norm_attacker_won"] for row in v["target_rows"]] for s, v in have.items()})
    tests = []
    for a, b in PAIRS:
        if a in agg and b in agg:
            common = [s for s in agg[a]["vec"] if s in agg[b]["vec"]]
            va = sum((agg[a]["vec"][s] for s in common), [])
            vb = sum((agg[b]["vec"][s] for s in common), [])
            tests.append((a, b, *mcnemar(va, vb), len(va)))

    meta = {s: sets[s].get("_meta", {}) for s in names}
    r2rows, r2meta = r2_table()

    # ---------- markdown ----------
    L = ["# Results: verification runs", "",
         "Generated by `verification/analyze.py` from `verification/runs/`. The analysis follows "
         "[`PREREGISTRATION.md`](PREREGISTRATION.md).", ""]
    L += ["## Phase B: R2 anchor run (unmodified upstream script, original llama.cpp build)", ""]
    if r2rows:
        L += [f"Script identical to upstream: **{r2meta.get('script_identical_to_upstream')}** · "
              f"llama.cpp `{r2meta.get('llama_cpp')}` `{r2meta.get('llama_args')}` · "
              f"model sha256 `{r2meta.get('model_sha256', '')[:12]}…`", "",
              "| Arm | Shipped ret/gen/clean | R2 ret/gen/clean | Identical answers (of 30) | R2 corpus |",
              "|---|---|---|---|---|"]
        for k, x, y, same in r2rows:
            if y:
                L.append(f"| {k} | {x['retrieval_asr']}/{x['gen_asr']}/{x['clean_acc']} | "
                         f"{y['retrieval_asr']}/{y['gen_asr']}/{y['clean_acc']} | {same} | {y['corpus_size']} |")
            else:
                L.append(f"| {k} | {x['retrieval_asr']}/{x['gen_asr']}/{x['clean_acc']} | not run | — | — |")
    else:
        L.append("_R2 not available._")
    L += ["", f"## Phase D: pre-registered arms × poison sets ({', '.join(names)})", ""]
    for s in names:
        m = meta[s]
        L.append(f"- **{s}**: git `{m.get('git_sha', '')[:7]}`, poison `{m.get('poison_set')}`, "
                 f"live canon fetched {m.get('live_canon_fetched_utc')}, fetch failures: {m.get('live_canon_failed')}")
    L += ["", "Gen ASR uses the pre-registered normalized/alias scoring. Raw is the upstream substring scoring. "
          "CIs are Wilson 95% on the pooled count.", "",
          "| Arm | Gen ASR (pooled) | 95% CI | per set | Retrieval ASR | Gen ASR raw | Target correct | Clean acc | Trusted chunks dropped (per set) |",
          "|---|---|---|---|---|---|---|---|---|"]
    for key, _ in ARMS:
        if key not in agg:
            continue
        a = agg[key]
        lo, hi = a["ci"]
        L.append(f"| {a['label']} | **{a['gen']}/{a['n']}** ({a['gen']/a['n']:.0%}) | {lo:.0%}–{hi:.0%} | "
                 f"{' · '.join(str(v) for v in a['per'].values())} | {a['ret']}/{a['n']} | {a['graw']}/{a['n']} | "
                 f"{a['cor']}/{a['n']} | {a['clean']}/{a['nclean']} | {', '.join(map(str, a['fr']))} |")
    L += ["", "### Paired tests (exact McNemar, generation ASR, per question pooled over sets)", "",
          "| A | B | A-only wins | B-only wins | n pairs | p |", "|---|---|---|---|---|---|"]
    for a, b, b01, b10, p, n in tests:
        L.append(f"| {agg[a]['label']} | {agg[b]['label']} | {b01} | {b10} | {n} | {p:.3g} |")
    (V / "RESULTS.md").write_text("\n".join(L) + "\n")

    # ---------- html ----------
    keys = [k for k, _ in ARMS if k in agg]
    row_h, top, left, width = 34, 30, 260, 420
    h = top + row_h * len(keys) + 40
    sx = lambda p: left + p * width
    bars = []
    for i, k in enumerate(keys):
        a = agg[k]
        y = top + i * row_h
        g, r = a["gen"] / a["n"], a["ret"] / a["n"]
        lo, hi = a["ci"]
        tip_g = f"{a['label']}: generation ASR {a['gen']}/{a['n']} ({g:.0%}), 95% CI {lo:.0%}–{hi:.0%}"
        tip_r = f"{a['label']}: retrieval ASR {a['ret']}/{a['n']} ({r:.0%})"
        bars.append(f'<text x="{left-10}" y="{y+17}" class="lbl" text-anchor="end">{html.escape(a["label"])}</text>')
        bars.append(f'<g class="hit" tabindex="0"><title>{html.escape(tip_r)}</title>'
                    f'<rect x="{left}" y="{y+3}" width="{max(r*width,0.5):.1f}" height="10" rx="3" class="s2"/></g>')
        bars.append(f'<g class="hit" tabindex="0"><title>{html.escape(tip_g)}</title>'
                    f'<rect x="{left}" y="{y+15}" width="{max(g*width,0.5):.1f}" height="10" rx="3" class="s1"/>'
                    f'<line x1="{sx(lo):.1f}" x2="{sx(hi):.1f}" y1="{y+20}" y2="{y+20}" class="ci"/>'
                    f'<line x1="{sx(lo):.1f}" x2="{sx(lo):.1f}" y1="{y+16}" y2="{y+24}" class="ci"/>'
                    f'<line x1="{sx(hi):.1f}" x2="{sx(hi):.1f}" y1="{y+16}" y2="{y+24}" class="ci"/></g>')
        bars.append(f'<text x="{sx(max(g, hi))+6:.1f}" y="{y+24}" class="val">{a["gen"]}/{a["n"]}</text>')
    grid = "".join(f'<line x1="{sx(t)}" x2="{sx(t)}" y1="{top-6}" y2="{h-34}" class="grid"/>'
                   f'<text x="{sx(t)}" y="{h-18}" class="axis" text-anchor="middle">{int(t*100)}%</text>'
                   for t in (0, .25, .5, .75, 1))
    svg = (f'<svg viewBox="0 0 {left+width+70} {h}" role="img" aria-label="Attack success rate by arm">'
           f'{grid}{"".join(bars)}</svg>')
    md_tables = (V / "RESULTS.md").read_text()

    import re as _re

    def inline(t):
        t = html.escape(t)
        t = _re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', t)
        t = _re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", t)
        return _re.sub(r"`([^`]+)`", r"<code>\1</code>", t)

    def md_to_html_tables(md):
        out, in_t = [], False
        for line in md.splitlines():
            if line.startswith("|"):
                cells = [c.strip() for c in line.strip("|").split("|")]
                if set("".join(cells)) <= set("-: "):
                    continue
                tag = "th" if not in_t else "td"
                if not in_t:
                    out.append("<div class='tw'><table>")
                    in_t = True
                out.append("<tr>" + "".join(f"<{tag}>{inline(c)}</{tag}>" for c in cells) + "</tr>")
            else:
                if in_t:
                    out.append("</table></div>")
                    in_t = False
                if line.startswith("## "):
                    out.append(f"<h2>{html.escape(line[3:])}</h2>")
                elif line.startswith("### "):
                    out.append(f"<h3>{html.escape(line[4:])}</h3>")
                elif line.startswith("- "):
                    out.append(f"<p class='note'>{inline(line[2:])}</p>")
                elif line.strip() and not line.startswith("# "):
                    out.append(f"<p class='note'>{inline(line)}</p>")
        if in_t:
            out.append("</table></div>")
        return "\n".join(out)

    page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>RAG Poisoning Verification</title>
<style>
:root{{color-scheme:light;--surface:#fcfcfb;--ink:#0b0b0b;--ink2:#52514e;--muted:#8a8984;--rule:#e4e3df;--s1:#2a78d6;--s2:#eb6834}}
@media (prefers-color-scheme:dark){{:root:not([data-theme="light"]){{color-scheme:dark;--surface:#1a1a19;--ink:#f0efec;--ink2:#c3c2b7;--muted:#8f8e86;--rule:#33332f;--s1:#3987e5;--s2:#d95926}}}}
:root[data-theme="dark"]{{color-scheme:dark;--surface:#1a1a19;--ink:#f0efec;--ink2:#c3c2b7;--muted:#8f8e86;--rule:#33332f;--s1:#3987e5;--s2:#d95926}}
body{{margin:0;background:var(--surface);color:var(--ink);font:15px/1.5 system-ui,-apple-system,Segoe UI,sans-serif}}
main{{max-width:960px;margin:0 auto;padding:24px 16px 64px}}
h1{{font-size:24px;margin:0 0 4px}} h2{{font-size:18px;margin:32px 0 8px}} h3{{font-size:15px;margin:20px 0 6px}}
.sub,.note{{color:var(--ink2);margin:4px 0}}
.legend{{display:flex;gap:16px;color:var(--ink2);font-size:13px;margin:12px 0 4px;flex-wrap:wrap}}
.sw{{display:inline-block;width:12px;height:12px;border-radius:3px;vertical-align:-1px;margin-right:6px}}
svg{{width:100%;height:auto}} .lbl{{fill:var(--ink);font-size:12px}} .val{{fill:var(--ink2);font-size:12px}}
.axis{{fill:var(--muted);font-size:11px}} .grid{{stroke:var(--rule);stroke-width:1}}
.s1{{fill:var(--s1)}} .s2{{fill:var(--s2)}} .ci{{stroke:var(--ink);stroke-width:1.5}}
.hit:hover rect,.hit:focus rect{{opacity:.8}}
.tw{{overflow-x:auto}} table{{border-collapse:collapse;font-size:13px;margin:8px 0;min-width:560px}}
th,td{{border-bottom:1px solid var(--rule);padding:6px 8px;text-align:left;vertical-align:top}} th{{color:var(--ink2);font-weight:600}} code{{font-size:12px}} a{{color:var(--s1)}}
</style></head><body><main>
<h1>RAG Poisoning Verification</h1>
<p class="sub">Attack success by defense arm, pooled over {len(names)} poison set(s). Bars: generation ASR (with Wilson 95% CI) and retrieval ASR. Hover a bar for exact values.</p>
<div class="legend"><span><span class="sw" style="background:var(--s1)"></span>Generation ASR (attacker answer produced)</span><span><span class="sw" style="background:var(--s2)"></span>Retrieval ASR (poison in top-5)</span></div>
{svg}
{md_to_html_tables(md_tables)}
</main></body></html>"""
    (V / "results.html").write_text(page)
    print(md_tables)


if __name__ == "__main__":
    main()
